-- Catálogo de platos: hamburguesas (principal), combos, postres y bebidas
CREATE TABLE IF NOT EXISTS Platos (
    id          INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    tipo        VARCHAR(20)  NOT NULL,
    nombre      VARCHAR(70)  NOT NULL,
    precio      INTEGER      NOT NULL,
    descripcion VARCHAR(400) NOT NULL,
    CONSTRAINT platos_pk PRIMARY KEY (id),
    CONSTRAINT platos_tipo_valido CHECK (tipo IN ('principal', 'combo', 'postre', 'bebida')),
    CONSTRAINT platos_precio_no_negativo CHECK (precio >= 0),
    CONSTRAINT platos_nombre_no_vacio CHECK (btrim(nombre) <> ''),
    CONSTRAINT platos_descripcion_no_vacia CHECK (btrim(descripcion) <> '')
);

-- Usuarios: password guarda el hash de bcrypt, nunca la contraseña original
CREATE TABLE IF NOT EXISTS Usuarios (
    id       INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    nombre   VARCHAR(50)  NOT NULL,
    apellido VARCHAR(50)  NOT NULL,
    email    VARCHAR(256) NOT NULL,
    password VARCHAR(256) NOT NULL,
    admin    BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT usuarios_pk PRIMARY KEY (id),
    CONSTRAINT usuarios_email_unico UNIQUE (email),
    CONSTRAINT usuarios_nombre_no_vacio CHECK (btrim(nombre) <> ''),
    CONSTRAINT usuarios_apellido_no_vacio CHECK (btrim(apellido) <> '')
);

-- Pedidos: un usuario tiene muchos pedidos (Pedidos.id_usuario -> Usuarios.id)
CREATE TABLE IF NOT EXISTS Pedidos (
    id         INTEGER     GENERATED BY DEFAULT AS IDENTITY,
    id_usuario INTEGER     NOT NULL,
    fecha      DATE        NOT NULL DEFAULT CURRENT_DATE,
    estado     VARCHAR(50) NOT NULL DEFAULT 'pendiente',
    CONSTRAINT pedidos_pk PRIMARY KEY (id),
    CONSTRAINT pedidos_usuario_fk FOREIGN KEY (id_usuario)
        REFERENCES Usuarios (id) ON DELETE RESTRICT,
    CONSTRAINT pedidos_estado_valido
        CHECK (estado IN ('pendiente', 'aceptado', 'en camino', 'entregado'))
);

-- Tabla intermedia: un pedido tiene muchos platos y un plato aparece en muchos pedidos.
-- Cada fila es un "ítem": el mismo plato puede aparecer dos veces en un pedido si
-- se personalizó distinto (por ejemplo una con cheddar extra y otra sin cebolla).
CREATE TABLE IF NOT EXISTS PlatosXPedidos (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_pedido       INTEGER NOT NULL,
    id_plato        INTEGER NOT NULL,
    cantidad        INTEGER NOT NULL,
    -- Precio de una unidad al momento del pedido (precio del plato + extras)
    precio_unitario INTEGER,
    aclaracion      VARCHAR(140),
    CONSTRAINT platosxpedidos_pk PRIMARY KEY (id),
    -- Al borrar un pedido se borran sus filas aquí: nunca quedan relaciones huérfanas
    CONSTRAINT platosxpedidos_pedido_fk FOREIGN KEY (id_pedido)
        REFERENCES Pedidos (id) ON DELETE CASCADE,
    -- Un plato incluido en algún pedido no se puede borrar (la API responde 409)
    CONSTRAINT platosxpedidos_plato_fk FOREIGN KEY (id_plato)
        REFERENCES Platos (id) ON DELETE RESTRICT,
    CONSTRAINT platosxpedidos_cantidad_positiva CHECK (cantidad > 0),
    CONSTRAINT platosxpedidos_precio_no_negativo CHECK (precio_unitario >= 0)
);

-- Ingredientes y extras. precio = lo que cuesta cada unidad agregada como extra.
-- disponible = false deja de ofrecerlo como extra sin borrarlo (por ejemplo, si se agotó).
CREATE TABLE IF NOT EXISTS Ingredientes (
    id         INTEGER     GENERATED BY DEFAULT AS IDENTITY,
    nombre     VARCHAR(60) NOT NULL,
    precio     INTEGER     NOT NULL DEFAULT 0,
    disponible BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT ingredientes_pk PRIMARY KEY (id),
    CONSTRAINT ingredientes_precio_no_negativo CHECK (precio >= 0),
    CONSTRAINT ingredientes_nombre_no_vacio CHECK (btrim(nombre) <> '')
);

-- Qué ingredientes admite cada plato:
--   incluido = true → viene en el plato y el cliente lo puede quitar.
--   maximo         → cuántas unidades extra se pueden agregar (0 = no se ofrece como extra).
CREATE TABLE IF NOT EXISTS IngredientesXPlatos (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_plato       INTEGER NOT NULL,
    id_ingrediente INTEGER NOT NULL,
    incluido       BOOLEAN NOT NULL DEFAULT FALSE,
    maximo         INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT ingredientesxplatos_pk PRIMARY KEY (id),
    CONSTRAINT ingredientesxplatos_plato_fk FOREIGN KEY (id_plato)
        REFERENCES Platos (id) ON DELETE CASCADE,
    CONSTRAINT ingredientesxplatos_ingrediente_fk FOREIGN KEY (id_ingrediente)
        REFERENCES Ingredientes (id) ON DELETE CASCADE,
    CONSTRAINT ingredientesxplatos_unico UNIQUE (id_plato, id_ingrediente),
    CONSTRAINT ingredientesxplatos_maximo_valido CHECK (maximo BETWEEN 0 AND 10),
    -- Si no viene incluido, tiene que poder agregarse: si no, la fila no tiene sentido
    CONSTRAINT ingredientesxplatos_con_uso CHECK (incluido OR maximo > 0)
);

-- Personalización de cada ítem de un pedido: extras agregados o ingredientes quitados.
-- precio guarda el valor unitario del extra al momento del pedido.
CREATE TABLE IF NOT EXISTS Personalizaciones (
    id             INTEGER     GENERATED BY DEFAULT AS IDENTITY,
    id_item        INTEGER     NOT NULL,
    id_ingrediente INTEGER     NOT NULL,
    accion         VARCHAR(10) NOT NULL,
    cantidad       INTEGER     NOT NULL DEFAULT 1,
    precio         INTEGER     NOT NULL DEFAULT 0,
    CONSTRAINT personalizaciones_pk PRIMARY KEY (id),
    CONSTRAINT personalizaciones_item_fk FOREIGN KEY (id_item)
        REFERENCES PlatosXPedidos (id) ON DELETE CASCADE,
    -- Un ingrediente que figura en pedidos no se borra (se puede marcar como no disponible)
    CONSTRAINT personalizaciones_ingrediente_fk FOREIGN KEY (id_ingrediente)
        REFERENCES Ingredientes (id) ON DELETE RESTRICT,
    CONSTRAINT personalizaciones_accion_valida CHECK (accion IN ('agregar', 'quitar')),
    CONSTRAINT personalizaciones_cantidad_positiva CHECK (cantidad > 0),
    CONSTRAINT personalizaciones_precio_no_negativo CHECK (precio >= 0),
    CONSTRAINT personalizaciones_unica_por_item UNIQUE (id_item, id_ingrediente)
);

